def build_induced_graph(hyperedges, default_weight=1):
    edge_weights = defaultdict(list)
    for edge_nodes in hyperedges.values():
        for u, v in combinations(sorted(edge_nodes), 2):
            edge_weights[(u, v)].append(default_weight)
            edge_weights[(v, u)].append(default_weight)

    G = defaultdict(list)
    for (u, v), weights in edge_weights.items():
        G[u].append((v, min(weights)))
    return G

def reconstruct_hyperpath(parent, source, target, edge_weights, hyperedges):
    """
    Reconstructs the hyperpath from source to target using the parent dictionary
    generated by dijkstra_hypergraph.
    """
    path = []
    hyperedge_sequence = []
    current_node = target
    total_distance = 0

    # If target is not reachable or is the source, handle gracefully
    if current_node not in parent and current_node != source:
        return [], [], float('inf') # Target not reachable

    while current_node != source:
        if current_node not in parent: # Should not happen if path exists and source is reached
            return [], [], float('inf')

        prev_node, hyperedge_id = parent[current_node]
        path.append(current_node)
        hyperedge_sequence.append(f"e{hyperedge_id}")
        total_distance += edge_weights[hyperedge_id] # Use the actual hyperedge weight
        current_node = prev_node

    path.append(source) # Add the source node
    path.reverse()
    hyperedge_sequence.reverse()

    return path, hyperedge_sequence, total_distance


def dijkstra_hypergraph(source, hyperedges, num_nodes, edge_weights):
    """
    Finds shortest hyperpaths in a hypergraph using a Dijkstra-like approach.

    Args:
        source (int): The starting node.
        hyperedges (dict): A dictionary where keys are hyperedge IDs (e.g., 0, 1)
                           and values are lists of nodes belonging to that hyperedge.
                           Example: {0: [0, 1, 2], 1: [1, 3]}
        num_nodes (int): The total number of nodes in the hypergraph.
        edge_weights (dict): A dictionary where keys are hyperedge IDs and values
                             are their corresponding weights.
                             Example: {0: 5, 1: 10}

    Returns:
        tuple: A tuple containing:
                - dist (dict): Shortest distances from the source to all other nodes.
                - parent (dict): A dictionary to reconstruct paths. parent[v] = (u, hyperedge_id)
                                 means node v was reached from node u using hyperedge_id.
    """
    # Initialization
    dist = {node: float('inf') for node in range(num_nodes)}
    parent = {} # Stores (previous_node, hyperedge_id_used)
    dist[source] = 0
    visited = set()

    heap = [(0, source)] # (current_distance, current_node)

    while heap:
        curr_dist, u = heapq.heappop(heap)

        if u in visited:
            continue
        visited.add(u)

        # Iterate through all hyperedges
        for hyperedge_id, nodes_in_hyperedge in hyperedges.items():
            # If the current node 'u' is part of this hyperedge
            if u in nodes_in_hyperedge:
                # The weight of this hyperedge
                weight = edge_weights.get(hyperedge_id, float('inf')) # Get weight from edge_weights dict

                # Consider all other nodes 'v' within this same hyperedge
                for v in nodes_in_hyperedge:
                    if v == u:
                        continue # Don't count "travel" from a node to itself within the same hyperedge

                    new_dist = curr_dist + weight
                    if new_dist < dist[v]:
                        dist[v] = new_dist
                        parent[v] = (u, hyperedge_id) # Store which hyperedge was used
                        heapq.heappush(heap, (new_dist, v))

    return dist, parent


# fct to get nbr of rows and colms
def get_matrix_dimensions(matrix_input):
    """
    Returns the number of rows and columns in a given matrix.

    Parameters:
        matrix_input (str or list or np.ndarray): Matrix as a string, list of lists, or NumPy array.

    Returns:
        (int, int): rows, columns
    """
    # Convert from string to list if needed
    if isinstance(matrix_input, str):
        matrix_input = ast.literal_eval(matrix_input)

    # Ensure it's a NumPy array
    matrix = np.array(matrix_input)

    # Unpack shape into two separate variables
    rows, cols = matrix.shape
    return rows, cols


