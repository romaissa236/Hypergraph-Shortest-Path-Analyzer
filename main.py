def convert_hypergraph_to_bipartite(V, hyperedges, edge_weights):
    """
    Convert a hypergraph to a bipartite graph.
    Each bipartite edge has weight = hyperedge_weight / 2
    """
    B = nx.Graph()
    B.add_nodes_from(V, bipartite=0)

    for eid, nodes in hyperedges.items():
        e_prime = f"e{eid}"
        B.add_node(e_prime, bipartite=1)

        w = edge_weights[eid]
        for v in nodes:
            B.add_edge(v, e_prime, weight=w / 2)

    return B


def dijkstra(B, source, target):
    """
    Finds the shortest path in a NetworkX graph B using Dijkstra's algorithm.

    Args:
        B (nx.Graph): The graph (in this case, the bipartite graph).
        source: The starting node.
        target: The target node (Dijkstra can stop early if target is found).

    Returns:
        tuple: A tuple containing:
                - dist (dict): A dictionary mapping each node to its shortest distance from the source.
                - parent (dict): A dictionary mapping each node to its predecessor on the
                                 shortest path from the source. This is used to reconstruct the path.
    """
    dist = {node: float('inf') for node in B.nodes}
    parent = {} # This dictionary will store the predecessor for path reconstruction
    dist[source] = 0

    heap = [(0, source)] # Priority queue: (distance, node)

    while heap:
        current_dist, u = heapq.heappop(heap)

        # Optimization: If we've reached the target, we can stop
        if u == target:
            break

        # If we've already found a shorter path to u, skip
        if current_dist > dist[u]:
            continue

        for v in B.neighbors(u):
            weight = B[u][v]['weight'] # Get the weight of the edge (u, v)
            new_dist = current_dist + weight

            if new_dist < dist[v]:
                dist[v] = new_dist
                parent[v] = u # <--- This is where the path is "saved"
                heapq.heappush(heap, (new_dist, v))

    return dist, parent


def draw_bipartite_graph(B):
    top_nodes = {n for n, d in B.nodes(data=True) if d["bipartite"] == 0}
    bottom_nodes = set(B) - top_nodes

    pos = dict()
    pos.update((n, (1, i)) for i, n in enumerate(top_nodes))
    pos.update((n, (2, i)) for i, n in enumerate(bottom_nodes))

    edge_labels = nx.get_edge_attributes(B, 'weight')

    plt.figure(figsize=(10, 6))
    nx.draw(B, pos, with_labels=True, node_color='skyblue', node_size=1500, font_size=10, edge_color='gray')
    nx.draw_networkx_edge_labels(B, pos, edge_labels=edge_labels)
    plt.title("Bipartite Graph from Hypergraph")
    plt.axis('off')
    plt.show()


